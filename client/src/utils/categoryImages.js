/**
 * Returns a high-resolution authentic food/drink image URL for any product or category
 * @param {string|object} categoryName
 * @param {string} existingImage
 * @param {string} productName
 * @returns {string} imageUrl
 */
export const getCategoryImage = (categoryName, existingImage, productName) => {
  const cleanProd = String(productName || "").toLowerCase().trim();

  // 1. Check exact product image mapping if available
  if (cleanProd && PRODUCT_IMAGE_MAP[cleanProd]) {
    return PRODUCT_IMAGE_MAP[cleanProd];
  }

  // 2. If existingImage is valid and not a placeholder or misplaced generic cup
  if (existingImage && !existingImage.includes("placeholder") && !existingImage.includes("via.placeholder")) {
    return existingImage;
  }

  // 3. Substring match on product name
  if (cleanProd) {
    for (const [key, url] of Object.entries(PRODUCT_IMAGE_MAP)) {
      if (cleanProd.includes(key) || key.includes(cleanProd)) {
        return url;
      }
    }
  }

  // 4. Category-level match
  const catStr = typeof categoryName === "object" ? categoryName?.name : categoryName;
  const cleanCat = String(catStr || "").toLowerCase().trim();

  if (CATEGORY_IMAGE_MAP[cleanCat]) {
    return CATEGORY_IMAGE_MAP[cleanCat];
  }

  for (const [key, url] of Object.entries(CATEGORY_IMAGE_MAP)) {
    if (cleanCat.includes(key) || key.includes(cleanCat)) {
      return url;
    }
  }

  // Sensible default
  return "https://images.unsplash.com/photo-1517701550927-30cf4ba1dba5?auto=format&fit=crop&w=500&q=80";
};
